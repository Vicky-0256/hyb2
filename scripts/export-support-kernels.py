"""Export lightweight UI assets without importing the folding runtime or its dependencies."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "third_party" / "cplfold"))
sys.path.insert(0, str(ROOT / "pipeline"))
from hyb2analysis.reference import FASTA_NAMES, MIN_PASTED_NT, MIN_SEQUENCE_NT, MIN_WINDOW_NT
from hyb2analysis.support_kernels import COMRADES_SCORE, DEFAULT_SUPPORT_KERNEL, KERNEL_OPTIONS
from hyb2analysis.engine_parameters import engine_parameters
from hyb2analysis.fold_text import FOLD_TEXT


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report stale files instead of writing them")
    args = parser.parse_args()
    options = [{"pairModel": "", **option} for option in KERNEL_OPTIONS]
    def dump(obj):
        return json.dumps(obj, indent=2, ensure_ascii=False)

    for option in options:
        if option["bonus"] not in ("log1p_hyb_bonus", "saturating_hyb_bonus") or not option["transform"] or not option["resultLabel"]:
            raise ValueError(f"support kernel {option['value']!r} needs a bonus kind, transform and result label")
    if any(type(value) is not int or value < 1 for value in COMRADES_SCORE.values()):
        raise ValueError("COMRADES score cap and endpoint count must be positive integers")
    catalog = {"defaultKernel": DEFAULT_SUPPORT_KERNEL, "options": options, "comradesScore": COMRADES_SCORE}
    minimums = {"minWindowNt": MIN_WINDOW_NT, "minPastedNt": MIN_PASTED_NT, "minSequenceNt": MIN_SEQUENCE_NT}
    for name, minimum in minimums.items():
        if type(minimum) is not int or minimum < 1:
            raise ValueError(f"{name} must be a positive integer")
    fold_text = dict(FOLD_TEXT, **minimums)
    assets = {"desktop/app/views/support-kernels.json": dump(dict(catalog, engines=engine_parameters("desktop"), foldText=fold_text)) + "\n",
              "web/support-kernels.js": "// Generated by scripts/export-support-kernels.py.\n"
                                        "globalThis.Hyb2SupportKernels = " + dump(catalog) + ";\n"
                                        "globalThis.Hyb2EngineParameters = " + dump(engine_parameters("web")) + ";\n"
                                        "globalThis.Hyb2FoldText = " + dump(dict(fold_text, fastaNames=FASTA_NAMES)) + ";\n"
                                        + (ROOT / "scripts/fold-text.js").read_text(encoding="utf-8")
                                        + (ROOT / "scripts/cplfold-settings.js").read_text(encoding="utf-8")}
    for name, content in assets.items():
        path = ROOT / name
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        if args.check:
            parser.exit(1, f"{name} is stale: run scripts/export-support-kernels.py with Python\n")
        path.write_bytes(content.encode())


if __name__ == "__main__":
    main()
